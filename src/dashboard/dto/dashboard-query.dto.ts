import { ApiPropertyOptional } from '@nestjs/swagger';
import { IsOptional, Matches } from 'class-validator';

import { ISO_DATE_PATTERN, ISO_MONTH_PATTERN } from '../../common';

/**
 * Запросы дашборда (ТЗ 5.2).
 *
 * **Доменных фильтров у дашборда нет намеренно.** ТЗ 5.2 называет его
 * «сводной витриной (агрегатором)» и ни одного фильтра в перечне не даёт:
 * дашборд отвечает на вопрос «что происходит в центре», а разрезы — дело
 * экранов, на которые с него переходят (`/left-courses`, `/graduates`,
 * `/leads`, `/timetable`, `/accounting/overview`), и у каждого из них фильтры
 * уже есть.
 *
 * У этого есть и вторая сторона, из-за которой фильтр по филиалу (ТЗ 3.3)
 * не заведён даже там, где он выразим: разрез по филиалу правилен для группы,
 * но **не** для денег — предоплата заведена на студента, а не на группу,
 * и такой фильтр молча выкидывал бы её из прихода (решение 0030). Фильтр,
 * который на одной витрине честен, а на соседней врёт, хуже отсутствующего.
 *
 * Остаётся только период — без него витрина не знает, что показывать.
 * Он задаётся **месяцами**, как во всех отчётах проекта (0021, 0022, 0025,
 * 0027, 0029–0033): вторая конвенция периода в соседнем разделе стоила бы
 * дороже, чем гибкость «за неделю».
 */

/** Период месяцами: обе границы включительно, обе необязательны. */
export class DashboardPeriodQueryDto {
  @ApiPropertyOptional({
    example: '2026-01',
    description:
      'Начало периода: месяц `YYYY-MM` включительно. По умолчанию — двенадцатый месяц ' +
      'назад от `to`.',
  })
  @IsOptional()
  @Matches(ISO_MONTH_PATTERN, { message: 'from: ожидается месяц в формате YYYY-MM' })
  from?: string;

  @ApiPropertyOptional({
    example: '2026-08',
    description: 'Конец периода: месяц `YYYY-MM` включительно. По умолчанию — текущий месяц.',
  })
  @IsOptional()
  @Matches(ISO_MONTH_PATTERN, { message: 'to: ожидается месяц в формате YYYY-MM' })
  to?: string;
}

/**
 * Сводка (ТЗ 5.2: «посещаемость за день, счётчики активных студентов/менторов,
 * активные группы»).
 *
 * Единственный параметр — день, за который показывается посещаемость.
 * Счётчики к нему не относятся: «сколько сейчас активных групп» — вопрос
 * о настоящем моменте, а не о выбранной дате, и подставлять в него прошлое
 * значило бы обещать историю, которой система не хранит (категория активности
 * не хранится — 0019, статус группы не версионируется — 0008).
 */
export class DashboardSummaryQueryDto {
  @ApiPropertyOptional({
    example: '2026-08-03',
    description:
      'День, за который считается посещаемость, `YYYY-MM-DD`. По умолчанию — сегодня (UTC).',
  })
  @IsOptional()
  @Matches(ISO_DATE_PATTERN, { message: 'date: ожидается дата в формате YYYY-MM-DD' })
  date?: string;
}

/**
 * Доход за месяц со сравнением (ТЗ 5.2).
 *
 * Месяц **календарный**, а не скользящее окно в тридцать дней (решение
 * пользователя): так число совпадает с обзором бухгалтерии (0030), который
 * считает месяцами, и два экрана не называют «доходом» разные суммы.
 * Сравнивается с предыдущим календарным месяцем.
 */
export class DashboardIncomeQueryDto {
  @ApiPropertyOptional({
    example: '2026-08',
    description: 'Месяц `YYYY-MM`. По умолчанию — текущий.',
  })
  @IsOptional()
  @Matches(ISO_MONTH_PATTERN, { message: 'month: ожидается месяц в формате YYYY-MM' })
  month?: string;
}
