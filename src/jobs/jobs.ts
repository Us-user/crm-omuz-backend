import type { DirectoryStatus } from '@prisma/client';

/** Вакансия в том объёме, в каком её видит правило «открыта ли она» (ТЗ 5.18). */
export interface JobOpening {
  status: DirectoryStatus;
  deadline: Date | null;
}

/**
 * Открыта ли вакансия на указанный день (ТЗ 5.18: «список **актуальных**
 * вакансий»).
 *
 * Чистая функция, а не колонка в БД: «срок вышел» — это сравнение `deadline`
 * с сегодняшним днём, и хранимая копия того же факта разошлась бы с датой
 * в первый же день. Тот же разбор, что у `isCouponValidOn` (0027).
 *
 * Граница **включающая**: вакансия «до 30 ноября» открыта тридцатого. Пустой
 * срок — открытый конец: бессрочный набор это законное состояние, а не запись,
 * которой забыли поставить дату.
 *
 * Статус входит в правило наравне со сроком: `INACTIVE` — это «место заняли
 * раньше объявленного срока», и вакансия, которая по дате ещё жива, но выведена
 * из работы, актуальной не является.
 */
export const isJobOpen = (job: JobOpening, on: Date): boolean =>
  job.status === 'ACTIVE' && (job.deadline === null || job.deadline.getTime() >= on.getTime());
