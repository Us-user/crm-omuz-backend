import { PartialType } from '@nestjs/swagger';

import { CreateJobDto } from './create-job.dto';

/**
 * Правка вакансии (ТЗ 5.18). Не переданное поле остаётся прежним, пустая строка
 * в необязательном поле очищает его — в том числе снимает срок.
 *
 * Обязательные поля создания (название, компания, контакты) здесь становятся
 * необязательными как **поля запроса**, но очистить их нельзя: `@MinLength(2)`
 * достаётся им от `PartialType`, и пустая строка отбивается как 400. То есть
 * «стереть контакты» невозможно ни у существующей вакансии, ни у новой.
 */
export class UpdateJobDto extends PartialType(CreateJobDto) {}
