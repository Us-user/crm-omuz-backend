import type { MailMessage } from './mailer.types';

/**
 * Абстракция «отправитель писем» (ТЗ 3.4): прикладной код знает только этот
 * контракт, а провайдер (SMTP, внешний API) подменяется в `MailerModule`.
 *
 * Объявлено абстрактным классом, а не интерфейсом: класс существует в рантайме
 * и служит DI-токеном, поэтому не нужен отдельный `Symbol` и `@Inject(...)`
 * в каждом потребителе.
 */
export abstract class MailerService {
  /**
   * Отправляет письмо.
   *
   * @throws Error если провайдер не смог принять сообщение — вызывающий код
   *   решает, ошибка это для пользователя или повод для повтора.
   */
  abstract send(message: MailMessage): Promise<void>;
}
