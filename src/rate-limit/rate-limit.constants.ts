import type { RateLimitRule } from './rate-limit';

const MINUTE = 60;
const HOUR = 60 * 60;

/**
 * Лимиты аутентификации и сброса пароля (ТЗ 3.8).
 *
 * Числа выбраны так, чтобы человек их не заметил, а перебор упёрся. Опорные
 * соображения, из которых они выведены:
 *
 * - **за одним адресом обычно сидит не один человек.** Студенты приходят
 *   в компьютерный класс, сотрудники работают из офиса за NAT — поэтому
 *   лимиты по адресу заметно щедрее, чем «сколько раз ошибается человек»;
 * - **счётчик расходуют и неверно заполненные формы.** Guard отрабатывает
 *   до `ValidationPipe`, и это осознанно: иначе перебор шёл бы заведомо
 *   ломаным запросом мимо всякого лимита;
 * - **argon2id и так делает подбор дорогим** (0002). Лимит здесь — не
 *   единственная защита, а верхняя граница на глупость.
 */

/**
 * Регистрация. Счётчика по логину нет: у нового человека логина ещё нет,
 * а лимит «на телефон» превратил бы форму в проверку, кто зарегистрирован.
 */
export const REGISTER_RATE_LIMIT: RateLimitRule = {
  action: 'auth.register',
  ip: { limit: 10, windowSeconds: HOUR },
};

/**
 * Вход. Счётчик по телефону **обнуляется при успешном входе**
 * (`AuthService.login`): иначе чужими запросами можно было бы закрыть человеку
 * вход, просто перебирая его номер, — лимит стал бы оружием против того,
 * кого защищает.
 */
export const LOGIN_RATE_LIMIT: RateLimitRule = {
  action: 'auth.login',
  ip: { limit: 20, windowSeconds: 5 * MINUTE },
  subject: { field: 'phone', kind: 'phone', limit: 10, windowSeconds: 15 * MINUTE },
};

/**
 * Обновление пары токенов. Лимит щедрый: у работающего человека это
 * происходит раз в час само, и весь офис за одним адресом должен уместиться.
 * Счётчика по логину нет — в теле только токен.
 */
export const REFRESH_RATE_LIMIT: RateLimitRule = {
  action: 'auth.refresh',
  ip: { limit: 60, windowSeconds: MINUTE },
};

/**
 * Запрос кода восстановления. Второй рубеж поверх лимита «3 кода в час
 * на аккаунт», который живёт в таблице с сессии 0003 и остаётся там: тот
 * считает **выпущенные коды существующему аккаунту**, этот — **запросы
 * про адрес**, независимо от того, есть такой аккаунт или нет.
 *
 * Отсюда важное следствие: 429 здесь **ничего не выдаёт**. Он срабатывает
 * на любой почте, поэтому не отвечает на вопрос «зарегистрирован ли адрес»,
 * ради которого молчит сам эндпоинт (0003).
 */
export const PASSWORD_FORGOT_RATE_LIMIT: RateLimitRule = {
  action: 'auth.password.forgot',
  ip: { limit: 5, windowSeconds: HOUR },
  subject: { field: 'email', kind: 'email', limit: 5, windowSeconds: HOUR },
};

/**
 * Ввод кода. Перебор одного кода уже ограничен тремя попытками в таблице
 * (0003, код после них гасится), но цикл «запросил новый код — снова три
 * попытки» тем лимитом не покрыт, а по многим адресам сразу — тем более.
 */
export const PASSWORD_RESET_RATE_LIMIT: RateLimitRule = {
  action: 'auth.password.reset',
  ip: { limit: 10, windowSeconds: HOUR },
  subject: { field: 'email', kind: 'email', limit: 10, windowSeconds: HOUR },
};
