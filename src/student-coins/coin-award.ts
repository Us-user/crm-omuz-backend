/**
 * Автоначисление коинов по итогу недели (ТЗ 5.9).
 *
 * Пороги заданы ТЗ дословно: `≥100 → 5 · 90–99 → 4 · 85–89 → 2 · <85 → 0`.
 * Правило вынесено чистой функцией и живёт в модуле коинов, а не в журнале:
 * начисляет их журнал (при финализации недели), но отвечают за них коины —
 * и вторая копия порогов рядом с журналом разошлась бы с этой на первой же
 * правке. Тот же ход, что с `deriveStudentStatus` в сессии 0014.
 */
export interface CoinAwardThreshold {
  /** Нижняя граница итога недели, включительно. */
  minSum: number;
  coins: number;
}

/** Пороги перечислены по убыванию — первый подошедший и есть ответ. */
export const COIN_AWARD_THRESHOLDS: readonly CoinAwardThreshold[] = [
  { minSum: 100, coins: 5 },
  { minSum: 90, coins: 4 },
  { minSum: 85, coins: 2 },
];

/**
 * Сколько коинов даёт итог недели. Ниже нижнего порога — ноль, и такая строка
 * в историю не пишется: начисление на ноль коинов ничего не сообщает,
 * а историю студента засоряло бы каждую неделю.
 */
export const coinsForWeekSum = (sum: number): number =>
  COIN_AWARD_THRESHOLDS.find((threshold) => sum >= threshold.minSum)?.coins ?? 0;
