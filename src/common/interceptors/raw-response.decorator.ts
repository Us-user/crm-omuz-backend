import { SetMetadata } from '@nestjs/common';

export const RAW_RESPONSE_KEY = 'raw_response';

/**
 * Помечает эндпоинт, ответ которого **не** заворачивается в `{ data }` (ТЗ 3.5).
 *
 * Единственный обоснованный случай — отдача файла: CSV, приехавший клиенту
 * внутри `{ "data": "Телефон,Фамилия…" }`, не открылся бы ни в Excel, ни
 * в редакторе, а браузер не сохранил бы его по `Content-Disposition`.
 * Исключение сделано явным декоратором, а не молчаливой проверкой типа
 * в интерцепторе: иначе любой эндпоинт, вернувший строку, случайно
 * переставал бы соблюдать общий формат ответа.
 */
export const RawResponse = () => SetMetadata(RAW_RESPONSE_KEY, true);
