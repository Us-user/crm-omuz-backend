import { SetMetadata } from '@nestjs/common';

export const NO_AUDIT_KEY = 'audit:skip';

/**
 * Изменяющий запрос, который действием не является и в журнал не пишется.
 *
 * Пока такой один — `POST /auth/refresh`: обновление пары токенов происходит
 * у каждого работающего пользователя раз в час (ТЗ 3.1) и говорит лишь о том,
 * что человек не закрыл вкладку. Журнал действий он бы заполнил целиком.
 *
 * Умолчание обратное — **пишется всё изменяющее**: забытый декоратор
 * оставляет лишнюю строку, а не тихо теряет действие (довод 0005 про guard).
 */
export const NoAudit = (): MethodDecorator & ClassDecorator => SetMetadata(NO_AUDIT_KEY, true);
