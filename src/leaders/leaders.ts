/**
 * Рейтинг центра (ТЗ 5.13) — чистые функции расстановки мест.
 *
 * Сам балл сюда не считается: он приходит агрегатом `_avg` по `WeekResult`,
 * а пороги категорий и правило «только финализированные недели» живут
 * в `performance.ts` с сессии 0019. Здесь только то, чего там не было, —
 * превращение списка баллов в места, корону и срез победителей месяца.
 */

/** Средний балл одного участника рейтинга: то, что отдаёт агрегат. */
export interface ScoredStudent {
  studentId: string;
  /** **Неокруглённое** среднее: по нему идут сравнения (см. `roundScore`). */
  average: number;
  /** Сколько финализированных недель попало в это среднее. */
  weeksCount: number;
}

/** Тот же участник с проставленным местом. */
export interface RankedStudent extends ScoredStudent {
  /** № в рейтинге, с 1. При равенстве баллов место одно на всех. */
  place: number;
}

/**
 * Сколько мест фиксирует снимок месяца по умолчанию — ТЗ 5.13 называет «топ-3».
 * Верхняя граница есть, чтобы «закрыть месяц» не означало «сохранить весь центр».
 */
export const DEFAULT_WINNER_PLACES = 3;
export const MAX_WINNER_PLACES = 10;

/**
 * Расстановка мест по убыванию балла.
 *
 * Место — «сколько студентов строго выше, плюс один» (правило сессии 0019):
 * при равенстве баллов оба занимают одно место, и следующий за ними получает
 * не следующий номер, а свой настоящий — 1, 1, 3. Придуманное правило разрыва
 * ничьей (по фамилии, по дате зачисления) поставило бы одного из двух одинаково
 * успевающих ниже без всякого основания.
 *
 * Сравнения идут по неокруглённому баллу: 87.334 и 87.335 показываются
 * одинаковыми 87.33, и округление до сравнения объявило бы первыми обоих.
 *
 * Внутри одного места порядок задан идентификатором, а не оставлен на волю
 * плана запроса: список **постраничный**, и без устойчивого порядка одна и та же
 * строка могла бы прийти на двух страницах подряд, а соседняя — не прийти вовсе.
 */
export function rankByScore(rows: readonly ScoredStudent[]): RankedStudent[] {
  const sorted = [...rows].sort((a, b) => b.average - a.average || compareIds(a, b));

  let place = 0;
  let previous: number | null = null;

  return sorted.map((row, index) => {
    if (previous === null || row.average < previous) {
      place = index + 1;
      previous = row.average;
    }

    return { ...row, place };
  });
}

/**
 * Срез «первые N мест» для снимка месяца.
 *
 * Отбор идёт по **месту**, а не по числу строк: если на третьем месте двое,
 * обрезание списка до трёх строк выкинуло бы одного из них по признаку,
 * которого нет, — а «при равенстве баллов место одно на двоих» уже решено.
 * Поэтому «топ-3» с ничьёй может дать и четыре строки, и больше.
 */
export const takePlaces = (rows: readonly RankedStudent[], maxPlace: number): RankedStudent[] =>
  rows.filter((row) => row.place <= maxPlace);

const compareIds = (a: ScoredStudent, b: ScoredStudent): number =>
  a.studentId < b.studentId ? -1 : a.studentId > b.studentId ? 1 : 0;
