import type { OutboundMessage } from './messaging.types';

/**
 * Абстракция «отправитель сообщений» (ТЗ 3.4: «Провайдер за абстракцией,
 * легко заменяется»).
 *
 * Прикладной код знает только этот контракт, а провайдер выбирается в одном
 * месте — в `MessagingModule`. Тот же приём и та же форма, что у `MailerService`
 * (0003): абстрактный класс, а не интерфейс, потому что класс существует
 * в рантайме и служит DI-токеном — не нужен ни отдельный `Symbol`,
 * ни `@Inject(...)` в каждом потребителе.
 *
 * Почему отдельный контракт рядом с `MailerService`, а не расширение его:
 * письмо — это `to/subject/text`, а сообщение — это ещё и **канал**, от которого
 * зависит, что означает адрес. Втащить канал в письмо значило бы, что у половины
 * вызовов половина полей не имеет смысла (тот же довод, по которому в 0030
 * не был заведён обобщённый `Transaction`).
 */
export abstract class MessageSender {
  /**
   * Отправляет сообщение.
   *
   * @throws PermanentDeliveryError если повторять бессмысленно (неверный адрес).
   * @throws Error при временном отказе — задача очереди будет повторена.
   */
  abstract send(message: OutboundMessage): Promise<void>;
}
