import { LeadType } from '@prisma/client';

/**
 * Дата перехода в клиенты после смены стадии (ТЗ 5.7).
 *
 * Чистая функция, потому что правило маленькое, но неочевидное в трёх местах
 * сразу: `undefined` здесь означает «колонку не трогать», и именно оно должно
 * возвращаться, когда стадия не менялась. Иначе обычное сохранение карточки
 * («поправили телефон») переписывало бы дату, когда человек стал клиентом.
 *
 * - стадия не передана или не изменилась → `undefined`;
 * - `LEAD → CLIENT` → `now`: дату события ставит система, а не оператор,
 *   иначе введённая руками она разошлась бы с самим событием;
 * - `CLIENT → LEAD` → `null`: возврат в лиды снимает дату, потому что иначе
 *   в данных осталась бы дата перехода, которого нет.
 */
export const becameClientAtOf = (
  current: LeadType,
  next: LeadType | undefined,
  now: Date,
): Date | null | undefined => {
  if (next === undefined || next === current) return undefined;

  return next === LeadType.CLIENT ? now : null;
};
