import { ApiProperty } from '@nestjs/swagger';
import { IsString, MaxLength, MinLength } from 'class-validator';

/**
 * Верхняя граница файла. 200 КБ — это тысячи строк телефонов: больше похоже
 * на выгрузку всей базы, чем на набор одной группы, и разбирать такое в памяти
 * ради одного запроса не стоит.
 */
export const MAX_IMPORT_CSV_LENGTH = 200_000;

/**
 * Верхняя граница числа строк. Отличается от `MAX_STUDENTS_PER_REQUEST` (100)
 * осознанно: зачисление руками — это выбор из списка на экране, а импорт —
 * файл, в который могли попасть и уже зачисленные, и повторы.
 */
export const MAX_IMPORT_ROWS = 500;

/**
 * Импорт состава группы (ТЗ 5.5: «Import/Export»).
 *
 * Текст CSV в JSON-теле, а не `multipart/form-data` (решение сессии 0013):
 * приём файлов — отдельный сквозной кусок инфраструктуры (куда складывать,
 * лимиты размера и MIME), который сессия 0009 уже осознанно отложила, решив
 * держать материалы уроков ссылками. Файл здесь никуда не сохраняется:
 * он читается, применяется и забывается.
 */
export class ImportGroupStudentsDto {
  @ApiProperty({
    example: 'Телефон\n+992901234567\n+992985550101',
    maxLength: MAX_IMPORT_CSV_LENGTH,
    description:
      'Содержимое CSV-файла. Первая строка — заголовок; в нём должна быть колонка ' +
      'с телефоном (`Телефон`, `phone`, `номер`). Остальные колонки игнорируются, ' +
      'поэтому файл из `GET …/students/export` подходит без правки. Разделитель — ' +
      'запятая или точка с запятой (её ставит Excel в русской локали), BOM снимается.',
  })
  @IsString()
  @MinLength(1)
  @MaxLength(MAX_IMPORT_CSV_LENGTH)
  csv!: string;
}
